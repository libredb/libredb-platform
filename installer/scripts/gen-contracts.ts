// Generates src/contracts/studio.ts and src/contracts/platform.ts from contracts/env-inventory.yaml: the key unions,
// the descriptor of every variable and the list of variables Studio refuses in governance mode. The env renderers
// read only these descriptors, so a variable outside the inventory is a type error.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parse } from "yaml";
import { z } from "zod";
import { formatPath } from "../src/config/schema";

export const INVENTORY_FILE = "contracts/env-inventory.yaml";

export const CONTRACT_FILES = {
  studio: "src/contracts/studio.ts",
  platform: "src/contracts/platform.ts",
} as const;

const APPS = ["studio", "platform", "platform-migrate"] as const;
type App = (typeof APPS)[number];

const REQUIREMENTS = [
  "always",
  "oidc",
  "governance",
  "self-hosted",
  "migrate",
  "internal-ca",
  "internal-console",
  "during-rotation",
  "https-proxy",
  "optional",
] as const;

const PRODUCERS = ["installer", "config", "default", "operator"] as const;

const CONDITIONS = [
  "always",
  "httpsProxy",
  "keycloakAdminUrl",
  "logoutHintVerified",
  "mobileClient",
  "volumeSize",
  "authSecretPrevious",
] as const;

const envName = z.string().regex(/^[A-Za-z_][A-Za-z0-9_]*$/, "expected an environment variable name");

const variable = z
  .object({
    name: envName,
    apps: z
      .array(z.enum(APPS))
      .min(1)
      .refine((apps) => new Set(apps).size === apps.length, "expected distinct apps"),
    required: z.enum(REQUIREMENTS),
    secret: z.boolean(),
    producer: z.enum(PRODUCERS),
    value: z.string().min(1).nullable().optional(),
    when: z.enum(CONDITIONS).optional(),
  })
  .strict();

const inventory = z
  .object({
    variables: z.array(variable).min(1),
    studioForbidden: z.array(envName),
  })
  .strict();

type Variable = z.output<typeof variable>;
type Inventory = z.output<typeof inventory>;

/** The descriptor a generated file holds for one variable. */
interface Descriptor {
  required: Variable["required"];
  secret: boolean;
  producer: Variable["producer"];
  value: string | null;
  when: Variable["when"] | null;
}

function written(producer: Variable["producer"]): boolean {
  return producer === "installer" || producer === "config";
}

function checkVariable(entry: Variable): Descriptor {
  if (written(entry.producer)) {
    if (typeof entry.value !== "string") throw new Error(`${entry.name}: producer ${entry.producer} needs a value`);
    return { ...pick(entry), value: entry.value, when: entry.when ?? "always" };
  }
  if (entry.when !== undefined) {
    throw new Error(`${entry.name}: producer ${entry.producer} is never written, so it takes no when`);
  }
  if (entry.producer === "operator" && entry.value !== undefined) {
    throw new Error(`${entry.name}: producer operator sets the value by hand, so it takes no value`);
  }
  return { ...pick(entry), value: entry.value ?? null, when: null };
}

function pick(entry: Variable): Pick<Descriptor, "required" | "secret" | "producer"> {
  return { required: entry.required, secret: entry.secret, producer: entry.producer };
}

function parseInventory(text: string): Inventory {
  const result = inventory.safeParse(parse(text));
  if (!result.success) {
    throw new Error(result.error.issues.map((issue) => `${formatPath(issue.path)}: ${issue.message}`).join("\n"));
  }
  return result.data;
}

/** The descriptors of one app, in inventory order. */
function descriptorsOf(variables: readonly Variable[], app: App): Map<string, Descriptor> {
  const out = new Map<string, Descriptor>();
  for (const entry of variables.filter((candidate) => candidate.apps.includes(app))) {
    if (out.has(entry.name)) throw new Error(`${entry.name} is listed twice for ${app}`);
    out.set(entry.name, checkVariable(entry));
  }
  return out;
}

const HEADER = `// Generated by scripts/gen-contracts.ts from ${INVENTORY_FILE}. Do not edit: run \`bun run gen:contracts\`.`;

const TYPES = `export type EnvRequirement = ${REQUIREMENTS.map((r) => JSON.stringify(r)).join(" | ")};

export type EnvProducer = ${PRODUCERS.map((p) => JSON.stringify(p)).join(" | ")};

/** When the installer writes a variable. */
export type EnvWriteCondition = ${CONDITIONS.map((c) => JSON.stringify(c)).join(" | ")};

export interface EnvDescriptor {
  /** When the app requires the variable. */
  readonly required: EnvRequirement;
  /** True when the value is a secret or embeds one. */
  readonly secret: boolean;
  readonly producer: EnvProducer;
  /** The value template, where {{name}} names an input of the renderer; null when the installer never sets it. */
  readonly value: string | null;
  /** When the installer writes the variable, or null when it never does. */
  readonly when: EnvWriteCondition | null;
}`;

function renderTable(constName: string, typeName: string, descriptors: Map<string, Descriptor>): string {
  const keys = [...descriptors.keys()];
  const entries = keys.map((key) => {
    const d = descriptors.get(key) as Descriptor;
    const fields = [
      `required: ${JSON.stringify(d.required)}`,
      `secret: ${d.secret}`,
      `producer: ${JSON.stringify(d.producer)}`,
      `value: ${JSON.stringify(d.value)}`,
      `when: ${JSON.stringify(d.when)}`,
    ];
    return `  ${key}: {\n${fields.map((field) => `    ${field},`).join("\n")}\n  },`;
  });
  return `export const ${constName}_KEYS = [\n${keys.map((key) => `  ${JSON.stringify(key)},`).join("\n")}\n] as const;

export type ${typeName} = (typeof ${constName}_KEYS)[number];

export const ${constName}: Readonly<Record<${typeName}, EnvDescriptor>> = {
${entries.join("\n")}
};`;
}

/** Renders both contract files from the inventory text. Throws on an inventory that cannot be used. */
export function generateContracts(text: string): { studio: string; platform: string } {
  const parsed = parseInventory(text);
  const studio = descriptorsOf(parsed.variables, "studio");
  const platform = descriptorsOf(parsed.variables, "platform");
  const migrate = descriptorsOf(parsed.variables, "platform-migrate");
  for (const name of parsed.studioForbidden) {
    if (studio.has(name)) throw new Error(`${name} is both a Studio variable and forbidden in governance mode`);
  }
  const forbidden = parsed.studioForbidden.map((name) => `  ${JSON.stringify(name)},`).join("\n");
  return {
    studio: `${HEADER}

${TYPES}

${renderTable("STUDIO_ENV", "StudioEnvKey", studio)}

/** The variables that must be unset or false in Studio governance mode. */
export const STUDIO_FORBIDDEN = [\n${forbidden}\n] as const;

export type StudioForbiddenKey = (typeof STUDIO_FORBIDDEN)[number];
`,
    platform: `${HEADER}

${TYPES}

/** The Platform runtime environment. */
${renderTable("PLATFORM_ENV", "PlatformEnvKey", platform)}

/** The environment of the Platform migrate job. */
${renderTable("PLATFORM_MIGRATE_ENV", "PlatformMigrateEnvKey", migrate)}
`,
  };
}

if (import.meta.main) {
  const root = join(import.meta.dir, "..");
  const generated = generateContracts(readFileSync(join(root, INVENTORY_FILE), "utf8"));
  writeFileSync(join(root, CONTRACT_FILES.studio), generated.studio);
  writeFileSync(join(root, CONTRACT_FILES.platform), generated.platform);
  console.log(`Wrote ${CONTRACT_FILES.studio} and ${CONTRACT_FILES.platform} from ${INVENTORY_FILE}.`);
}
