// Bundles the Helm chart's jobs (src/cli/kubernetes-job.ts) into one CommonJS file for the Platform image's node,
// gzipped as charts/libredb-platform/files/libredb-jobs.cjs.gz, which the chart mounts from a ConfigMap: compressed, so
// the Helm release record stays far below the 1 MiB of a Secret. The bundle is generated:
// test/unit/kubernetes/bundle.test.ts rebuilds it and fails when the committed file differs, so the chart always runs
// the installer's current code. Run `bun run build:helm-jobs` after changing anything the jobs import.
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { gunzipSync, gzipSync } from "node:zlib";
import { tmpdir } from "node:os";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
export const ENTRYPOINT = join(root, "src/cli/kubernetes-job.ts");
export const CHART_BUNDLE = join(root, "..", "charts", "libredb-platform", "files", "libredb-jobs.cjs.gz");

const BANNER =
  "// Generated by installer/scripts/build-helm-jobs.ts from installer/src/cli/kubernetes-job.ts; do not edit.\n";

/** Builds the bundle and returns its content. */
export function buildHelmJobs(): string {
  const dir = mkdtempSync(join(tmpdir(), "libredb-helm-jobs-"));
  try {
    const outfile = join(dir, "libredb-jobs.cjs");
    const result = Bun.spawnSync(
      ["bun", "build", "--target=node", "--format=cjs", "--minify", ENTRYPOINT, "--outfile", outfile],
      { cwd: root, stdout: "pipe", stderr: "pipe" },
    );
    if (result.exitCode !== 0) throw new Error(`bun build failed:\n${result.stderr.toString()}`);
    return BANNER + readFileSync(outfile, "utf8");
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

/** The bundle as the chart ships it: gzip at level 9, whose header carries no file name and no time. */
export function compressBundle(content: string): Buffer {
  return gzipSync(Buffer.from(content, "utf8"), { level: 9 });
}

/** The committed bundle, decompressed. */
export function committedBundle(): string {
  return gunzipSync(readFileSync(CHART_BUNDLE)).toString("utf8");
}

if (import.meta.main) {
  const compressed = compressBundle(buildHelmJobs());
  writeFileSync(CHART_BUNDLE, compressed);
  console.log(`wrote ${CHART_BUNDLE} (${compressed.length} bytes)`);
}
