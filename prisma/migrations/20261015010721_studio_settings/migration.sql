-- Added by hand: bridge.settings_v1 of bridge contract v1, the values of the allowlisted keys that contract 1 publishes.
CREATE VIEW bridge.settings_v1 WITH (security_barrier = true, security_invoker = false) AS
SELECT s.key, s.value, s."updatedAt" AS updated_at
FROM platform.studio_settings s
JOIN platform.studio_setting_keys k ON k.key = s.key
WHERE k."sinceContract" <= 1;

-- The grants of bridge contract v1 for this view, and nothing to PUBLIC.
GRANT SELECT ON bridge.settings_v1 TO libredb_studio, libredb_platform;

