-- Added by hand: the validation trigger on the camelCase columns.
-- A value must be allowlisted, of its key's JSON type, a whole number within the bounds for an integer key, and in the allowed set when the key has one.
-- It stamps updatedAt on every write, so the value of bridge.settings_v1.updated_at is the database's time.
CREATE FUNCTION platform.studio_settings_validate() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $$
DECLARE
  k platform.studio_setting_keys;
  v_expected text;
BEGIN
  SELECT * INTO k FROM platform.studio_setting_keys WHERE key = NEW.key;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'studio setting % is not allowlisted', NEW.key USING ERRCODE = '23503';
  END IF;
  v_expected := CASE k."valueType" WHEN 'integer' THEN 'number' ELSE k."valueType" END;
  IF jsonb_typeof(NEW.value) <> v_expected THEN
    RAISE EXCEPTION 'studio setting % must be a JSON %', NEW.key, k."valueType" USING ERRCODE = '22023';
  END IF;
  IF k."valueType" = 'integer' AND (
       (NEW.value #>> '{}')::numeric <> trunc((NEW.value #>> '{}')::numeric)
       OR (k."minValue" IS NOT NULL AND (NEW.value #>> '{}')::numeric < k."minValue")
       OR (k."maxValue" IS NOT NULL AND (NEW.value #>> '{}')::numeric > k."maxValue")) THEN
    RAISE EXCEPTION 'studio setting % is out of range', NEW.key USING ERRCODE = '22023';
  END IF;
  IF k."allowedValues" IS NOT NULL AND NOT (k."allowedValues" @> jsonb_build_array(NEW.value)) THEN
    RAISE EXCEPTION 'studio setting % has a value outside its allowed set', NEW.key USING ERRCODE = '22023';
  END IF;
  NEW."updatedAt" := now();
  RETURN NEW;
END $$;
CREATE TRIGGER studio_settings_validate BEFORE INSERT OR UPDATE ON platform.studio_settings
  FOR EACH ROW EXECUTE FUNCTION platform.studio_settings_validate();

